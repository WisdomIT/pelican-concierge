<?php

namespace WisdomIT\Concierge\Tools;

/**
 * 도구가 속한 갈래 (#45).
 *
 * 에이전트가 줄 수 있는 능력은 **요청자가 패널에서 스스로 할 수 있는 것**을 따른다(#36).
 * 그 원칙을 코드로 지탱하려면 도구를 낱개가 아니라 갈래로 다뤄야 한다 — 갈래마다
 * "누가 이걸 받는가"의 판정이 하나씩 붙고, 시스템 프롬프트의 절도 같은 갈래를 따른다.
 */
enum ToolGroup: string
{
    /** 이미 있는 서버를 돌보는 도구 — 상태·파일·전원·예약·모드·백업. */
    case Care = 'care';

    /** 서버를 새로 만드는 도구. */
    case Create = 'create';

    /** 패널 관리 도구 — 노드·사용자·역할 (#46 에서 채운다). */
    case Admin = 'admin';
}
